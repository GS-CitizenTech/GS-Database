    FUNCTION FN_VALIDAR_LEITURA(
        p_chuva_mm in NUMBER,
        p_nivel_agua_cm IN NUMBER,
        p_elevacao_cm_h IN NUMBER
    ) RETURN VARCHAR2;
    
    PROCEDURE PR_REGISTRAR_LEITURA(
        p_id_ponto IN NUMBER,
        p_chuva_mm IN NUMBER,
        p_nivel_agua_cm IN NUMBER,
        p_elevacao_cm_h IN NUMBER,
        p_origem IN VARCHAR2
    );

END PKG_MONITORAMENTO;
/

CREATE OR REPLACE PACKAGE BODY PKG_MONITORAMENTO AS

    FUNCTION FN_VALIDAR_LEITURA(
        p_chuva_mm IN NUMBER,
        p_nivel_agua_cm IN NUMBER,
        p_elevacao_cm_h IN NUMBER
        ) RETURN VARCHAR2
    IS
    BEGIN

        IF (p_chuva_mm IS NULL AND p_nivel_agua_cm IS NULL )
        OR NVL(p_chuva_mm, 0) <0
        OR NVL (p_nivel_agua_cm,0) <0
        OR NVL (p_elevacao_cm_h,0) <0 THEN
            
            RETURN 'INVALIDA';
        ELSE
            RETURN 'VALIDA';
        END IF;
    
    END FN_VALIDAR_LEITURA;
    
    PROCEDURE PR_REGISTRAR_LEITURA(
        p_id_ponto IN NUMBER,
        p_chuva_mm IN NUMBER,
        p_nivel_agua_cm IN NUMBER,
        p_elevacao_cm_h IN NUMBER,
        p_origem IN VARCHAR2
        )
    IS
        v_validacao VARCHAR2(20);
    BEGIN
    
        v_validacao := FN_VALIDAR_LEITURA(
            p_chuva_mm,
            p_nivel_agua_cm,
            p_elevacao_cm_h
            );
            
        IF v_validacao = 'VALIDA' THEN
            INSERT INTO LEITURA_ENCHENTE (ID_PONTO,CHUVA_MM,NIVEL_AGUA_CM,ELEVACAO_CM_H,DATA_HORA_LEITURA,ORIGEM)
            VALUES(p_id_ponto,p_chuva_mm,p_nivel_agua_cm,p_elevacao_cm_h,CURRENT_TIMESTAMP,p_origem);
        
        ELSE
           DBMS_OUTPUT.PUT_LINE  ('Leitura invalida. Registro nao realizado.');
        END IF;
        
     END PR_REGISTRAR_LEITURA;    
END PKG_MONITORAMENTO;
/


CREATE OR REPLACE TRIGGER TRG_AUDITAR_ALERTA_INSERT
    AFTER INSERT ON ALERTA
    FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_ALERTA(
    ID_ALERTA,
    OPERACAO,
    STATUS_ANTERIOR
    ,STATUS_NOVO 
    )
    VALUES (
    :NEW.ID_ALERTA,
    'INSERT',
    NULL,
    :NEW.STATUS
    );
END;
/

CREATE OR REPLACE TRIGGER TRG_AUDITAR_ALERTA_UPDATE
AFTER UPDATE OF STATUS ON ALERTA
FOR EACH ROW
BEGIN
    INSERT INTO AUDITORIA_ALERTA (
        ID_ALERTA,
        OPERACAO,
        STATUS_ANTERIOR,
        STATUS_NOVO
    )
    VALUES (
        :OLD.ID_ALERTA,
        'UPDATE',
        :OLD.STATUS,
        :NEW.STATUS
    );
END;
