CREATE TABLE USUARIO (
    ID_USUARIO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME VARCHAR2(100) NOT NULL,
    EMAIL VARCHAR2(150) NOT NULL,
    SENHA VARCHAR2(255) NOT NULL,
    PAPEL VARCHAR2(20) DEFAULT 'ROLE_USER' NOT NULL,
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,

    CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT CK_USUARIO_PAPEL CHECK (PAPEL IN ('ROLE_USER', 'ROLE_ADMIN')), 
    CONSTRAINT CK_USUARIO_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE PONTO_MONITORAMENTO(
    ID_PONTO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    CODIGO VARCHAR2(50) NOT NULL,
    NOME VARCHAR2(100) NOT NULL,
    BAIRRO VARCHAR2(100),
    CIDADE VARCHAR2(100) NOT NULL,
    UF CHAR(2)NOT NULL,
    LATITUDE NUMBER(10,7),
    LONGITUDE NUMBER(10,7),
    ATIVO CHAR(1) DEFAULT 'S' NOT NULL,
    DATA_CADASTRO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT PK_PONTO PRIMARY KEY(ID_PONTO),
    CONSTRAINT UK_PONTO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_PONTO_ATIVO CHECK (ATIVO IN ('S', 'N'))
);

CREATE TABLE LEITURA_ENCHENTE(
    ID_LEITURA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PONTO NUMBER NOT NULL,
    NIVEL_AGUA_CM NUMBER(8,2),
    CHUVA_MM NUMBER(8,2),
    ELEVACAO_CM_H NUMBER(8,2),
    DATA_HORA_LEITURA TIMESTAMP NOT NULL,
    ORIGEM VARCHAR2(50) NOT NULL,
    DATA_RECEBIMENTO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT PK_LEITURA_ENCHENTE PRIMARY KEY (ID_LEITURA),
    CONSTRAINT FK_LEITURA_PONTO FOREIGN KEY(ID_PONTO) REFERENCES PONTO_MONITORAMENTO(ID_PONTO),
    CONSTRAINT CK_LEITURA_VALORES CHECK((NIVEL_AGUA_CM IS NULL OR NIVEL_AGUA_CM >=0)
    AND (CHUVA_MM IS NULL OR CHUVA_MM >=0) AND (ELEVACAO_CM_H IS NULL OR ELEVACAO_CM_H >=0))
);

CREATE TABLE ALERTA(
    ID_ALERTA  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LEITURA NUMBER NOT NULL,
    CLASSIFICACAO VARCHAR2(20)NOT NULL,
    PROBABILIDADE NUMBER(5,2),
    MENSAGEM_EXPLICATIVA VARCHAR2(500),
    STATUS VARCHAR2(20) DEFAULT 'ATIVO' NOT NULL,
    DATA_GERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    DATA_RESOLUCAO TIMESTAMP,
    
    CONSTRAINT PK_ALERTA PRIMARY KEY (ID_ALERTA),
    CONSTRAINT FK_ALERTA_LEITURA FOREIGN KEY (ID_LEITURA) REFERENCES LEITURA_ENCHENTE(ID_LEITURA),
    CONSTRAINT UK_ALERTA_LEITURA UNIQUE (ID_LEITURA),
    CONSTRAINT CK_ALERTA_CLASSIFICACAO CHECK(CLASSIFICACAO IN ('BAIXO','MODERADO','ALTO', 'CRITICO')),
    CONSTRAINT CK_ALERTA_STATUS CHECK (STATUS IN ('ATIVO', 'RESOLVIDO')),
    CONSTRAINT CK_ALERTA_PROBABILIDADE CHECK(PROBABILIDADE IS NULL OR (PROBABILIDADE >=0 AND PROBABILIDADE <= 100)),
    CONSTRAINT CK_ALERTA_RESOLUCAO CHECK((STATUS = 'ATIVO' AND DATA_RESOLUCAO IS NULL) OR (STATUS = 'RESOLVIDO' AND DATA_RESOLUCAO IS NOT NULL))
);

CREATE TABLE AUDITORIA_ALERTA (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ALERTA NUMBER NOT NULL,
    OPERACAO VARCHAR2(20) NOT NULL,
    STATUS_ANTERIOR VARCHAR2(20),
    STATUS_NOVO VARCHAR2(20),
    DATA_OPERACAO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    
    CONSTRAINT PK_AUDITORIA_ALERTA PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT FK_AUDITORIA_ALERTA FOREIGN KEY (ID_ALERTA) REFERENCES ALERTA(ID_ALERTA),
    CONSTRAINT CK_AUDITORIA_ALERTA_OPERACAO CHECK (OPERACAO IN ('INSERT', 'UPDATE'))
);

CREATE TABLE NOTIFICACAO (
    ID_NOTIFICACAO NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO NUMBER NOT NULL,
    ID_ALERTA NUMBER NOT NULL,
    DATA_ENVIO TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    LIDA CHAR(1) DEFAULT 'N' NOT NULL,
    DATA_LEITURA TIMESTAMP,

    CONSTRAINT PK_NOTIFICACAO PRIMARY KEY (ID_NOTIFICACAO),
    CONSTRAINT FK_NOTIFICACAO_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO(ID_USUARIO),
    CONSTRAINT FK_NOTIFICACAO_ALERTA FOREIGN KEY (ID_ALERTA) REFERENCES ALERTA(ID_ALERTA),
    CONSTRAINT UK_NOTIFICACAO_USUARIO_ALERTA UNIQUE (ID_USUARIO, ID_ALERTA),
    CONSTRAINT CK_NOTIFICACAO_LIDA CHECK (LIDA IN ('S', 'N')),
    CONSTRAINT CK_NOTIFICACAO_DATA_LEITURA CHECK ((LIDA = 'N' AND DATA_LEITURA IS NULL) OR (LIDA = 'S' AND DATA_LEITURA IS NOT NULL))
);

CREATE OR REPLACE PACKAGE PKG_ALERTAS AS
    FUNCTION FN_CLASSIFICAR_RISCO(
        p_chuva_mm IN NUMBER,
        p_nivel_agua_cm IN NUMBER
        )RETURN VARCHAR2;
        
    PROCEDURE PR_GERAR_ALERTA(
        p_id_leitura IN NUMBER
        );
END PKG_ALERTAS;
/


CREATE OR REPLACE PACKAGE BODY PKG_ALERTAS AS

    FUNCTION FN_CLASSIFICAR_RISCO(
        p_chuva_mm IN NUMBER,
        p_nivel_agua_cm IN NUMBER
        )RETURN VARCHAR2
    IS
    BEGIN
        
        IF NVL(p_chuva_mm, 0) >= 50 OR NVL(p_nivel_agua_cm,0) >=40 THEN
        RETURN 'CRITICO';
        
        ELSIF NVL(p_chuva_mm,0) >=30 OR NVL(p_nivel_agua_cm,0) >=20 THEN 
        RETURN 'ALTO';
        
        ELSIF NVL(p_chuva_mm,0) >=10 OR NVL(p_nivel_agua_cm, 0) >=10 THEN
        RETURN 'MODERADO';
        
        ELSE
            RETURN 'BAIXO';
        END IF;

    END FN_CLASSIFICAR_RISCO;
    
    PROCEDURE PR_GERAR_ALERTA( p_id_leitura IN NUMBER)
    IS
        v_chuva NUMBER;
        v_nivel NUMBER;
        v_classificacao VARCHAR2(20);
        v_quantidade NUMBER;
        v_mensagem VARCHAR2(500);
    BEGIN
        
        SELECT CHUVA_MM, NIVEL_AGUA_CM
        INTO v_chuva, v_nivel
        FROM LEITURA_ENCHENTE
        WHERE ID_LEITURA = p_id_leitura;
        
        v_classificacao := FN_CLASSIFICAR_RISCO(
            v_chuva,
            v_nivel
        );
        
        SELECT COUNT(*) INTO v_quantidade FROM ALERTA
        WHERE ID_LEITURA = p_id_leitura;
        
        
        IF v_classificacao = 'BAIXO' THEN NULL;
        
        ELSIF v_quantidade = 0 THEN
            
            v_mensagem := 'Risco classificado como ' || v_classificacao;
            
            INSERT INTO ALERTA (ID_LEITURA,CLASSIFICACAO,MENSAGEM_EXPLICATIVA,STATUS)VALUES (p_id_leitura,v_classificacao,v_mensagem,'ATIVO' );

        END IF;

    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            DBMS_OUTPUT.PUT_LINE('Leitura nao encontrada.');
    END PR_GERAR_ALERTA;
END PKG_ALERTAS;
/

